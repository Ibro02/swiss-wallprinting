// Turns the hero video into WebP frame sequences for the scroll hero (PrintOnScroll):
// `vp run frames` (run it after the video changes). Needs ffmpeg on PATH
// (`winget install Gyan.FFmpeg`). Writes public/frames/hero/<variant>/0000.webp … and the
// manifest src/content/images/frames.ts.
//
// Why frames and not the video: a <video> scrubbed with `currentTime` must decode from the
// last keyframe at every seek (this file has one keyframe in 121 frames), so it stutters.
// Images drawn to a canvas show any frame at once, forward and backward.
//
// The same as these two commands (PowerShell; in bash, write %04d the same way):
//   ffmpeg -i src/assets/videos/landingPageVideo.mp4 -map 0:v:0 -fps_mode passthrough -vf scale=1280:-2 -c:v libwebp -quality 80 -compression_level 6 -start_number 0 public/frames/hero/desktop/%04d.webp
//   ffmpeg -i src/assets/videos/landingPageVideo.mp4 -map 0:v:0 -fps_mode passthrough -vf scale=960:-2 -c:v libwebp -quality 75 -compression_level 6 -start_number 0 public/frames/hero/mobile/%04d.webp

import { execFile } from 'node:child_process'
import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { promisify } from 'node:util'
import sharp from 'sharp'
import type { FrameSet } from '../src/content/images/types.ts'

const run = promisify(execFile)
const root = path.resolve(import.meta.dirname, '..')

const SOURCE = 'src/assets/videos/landingPageVideo.mp4'
const OUT = 'public/frames/hero'
const MANIFEST = 'src/content/images/frames.ts'

interface Variant {
  /** Folder under public/frames/hero/ and key in the manifest. */
  name: 'desktop' | 'mobile'
  /** Output width; the height keeps the video's proportions. Not larger than the source. */
  width: number
  /** libwebp quality, 0 … 100. */
  quality: number
}

const VARIANTS: readonly Variant[] = [
  // The source size (1280 × 720): about 8 MB for all frames.
  { name: 'desktop', width: 1280, quality: 80 },
  // Phones (PrintOnScroll `mobileQuery`): the same frames, about half the bytes. A phone
  // shows only a narrow slice of each frame, so a smaller width soon looks soft.
  { name: 'mobile', width: 960, quality: 75 },
]

try {
  await run('ffmpeg', ['-hide_banner', '-version'])
} catch {
  console.error(
    [
      'ffmpeg was not found, so no frames were made. The frames in public/frames/ are unchanged.',
      'Install it with `winget install Gyan.FFmpeg`, open a new terminal (so PATH has it), and run `vp run frames` again.',
    ].join('\n'),
  )
  process.exit(1)
}

await rm(path.join(root, OUT), { recursive: true, force: true })

const manifest: Partial<Record<Variant['name'], FrameSet>> = {}
for (const variant of VARIANTS) {
  const dir = path.join(root, OUT, variant.name)
  await mkdir(dir, { recursive: true })
  await run('ffmpeg', [
    '-hide_banner',
    '-v',
    'error',
    '-i',
    path.join(root, SOURCE),
    '-map',
    '0:v:0',
    '-fps_mode',
    'passthrough',
    '-vf',
    `scale=${variant.width}:-2`,
    '-c:v',
    'libwebp',
    '-quality',
    String(variant.quality),
    '-compression_level',
    '6',
    '-start_number',
    '0',
    path.join(dir, '%04d.webp'),
  ])

  const files = (await readdir(dir)).filter((file) => file.endsWith('.webp')).sort()
  const first = files[0]
  if (!first) throw new Error(`ffmpeg wrote no frames to ${dir}`)
  const { width, height } = await sharp(path.join(dir, first)).metadata()
  const sizes = await Promise.all(
    files.map(async (file) => (await stat(path.join(dir, file))).size),
  )
  const megabytes = sizes.reduce((sum, size) => sum + size, 0) / 1024 / 1024

  manifest[variant.name] = {
    pattern: `/frames/hero/${variant.name}/%04d.webp`,
    count: files.length,
    width,
    height,
  }
  console.log(
    `${OUT}/${variant.name}: ${files.length} frames, ${width} × ${height}, ${megabytes.toFixed(1)} MB`,
  )
}

await writeFile(
  path.join(root, MANIFEST),
  `// GENERATED by \`vp run frames\`. Do not edit by hand.

import type { FrameSet } from './types.ts'

export const heroFrames = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<'desktop' | 'mobile', FrameSet>
`,
)
console.log(`${MANIFEST} written`)

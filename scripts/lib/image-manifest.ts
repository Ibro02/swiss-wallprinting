// Writes the generated image manifests in src/content/images/ (used by the pipelines).

import { writeFile } from 'node:fs/promises'
import sharp from 'sharp'
import type { ImageAsset } from '../../src/content/images/types.ts'

/** Size and a tiny blur preview of an image file. */
export async function describeImage(file: string, src: string): Promise<ImageAsset> {
  const { width, height } = await sharp(file).metadata()
  const blur = await sharp(file).resize(12).webp({ quality: 40 }).toBuffer()
  return { src, width, height, blurDataURL: `data:image/webp;base64,${blur.toString('base64')}` }
}

/** A TypeScript module that exports `entries` as `name` (typed keys, no runtime cost). */
export async function writeManifest(
  file: string,
  name: string,
  script: string,
  entries: Record<string, ImageAsset>,
) {
  const sorted = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)))
  const source = `// GENERATED by \`vp run ${script}\`. Do not edit by hand.

import type { ImageAsset } from './types.ts'

export const ${name} = ${JSON.stringify(sorted, null, 2)} as const satisfies Record<string, ImageAsset>
`
  await writeFile(file, source)
}

// Vite+ toolchain config. Next.js does not read this file: it runs dev and
// build itself. This file configures `vp check` (Oxfmt, Oxlint, type check),
// `vp test` (Vitest), and `vp staged` (pre-commit).
import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vite-plus'

const notSource = [
  '.next/**',
  'node_modules/**',
  'coverage/**',
  'public/**',
  'Assets/**',
  'swiss-wallprinting/**',
  '.claude/**',
  'next-env.d.ts',
  'pnpm-lock.yaml',
]

export default defineConfig({
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  fmt: {
    semi: false,
    singleQuote: true,
    trailingComma: 'all',
    printWidth: 100,
    sortPackageJson: true,
    // Generated by the image pipelines (they write JSON-style objects).
    ignorePatterns: [
      ...notSource,
      '**/*.md',
      'src/content/images/mock.ts',
      'src/content/images/photos.ts',
      'src/content/images/frames.ts',
    ],
  },
  lint: {
    plugins: ['typescript', 'unicorn', 'oxc', 'import', 'react', 'nextjs', 'jsx-a11y', 'vitest'],
    ignorePatterns: notSource,
    options: {
      typeAware: true,
      typeCheck: true,
    },
    rules: {
      // Vitest accepts a failure message as the second argument: expect(value, message).
      'vitest/valid-expect': ['error', { maxArgs: 2 }],
    },
  },
  test: {
    include: ['src/**/*.test.{ts,tsx}', 'scripts/**/*.test.ts'],
    environment: 'node',
  },
  staged: {
    // Windows limits a command line to 8191 characters, and the paths in this OneDrive
    // folder are long: with many staged files, check the whole project once instead of
    // passing every path (the first commit failed with "The command line is too long").
    '*': (files) =>
      files.length > 30
        ? 'vp check --fix'
        : `vp check --fix ${files.map((file) => JSON.stringify(file)).join(' ')}`,
  },
})
